"""Living Wiki & Self-Documentation Engine inspired by Project Chimera's chimera-wiki-manager.

Scans the codebase AST, extracts docstrings, type annotations, and module topology,
and compiles living markdown wiki pages with Mermaid architecture diagrams.
"""

from __future__ import annotations
import ast
from pathlib import Path
from typing import Dict, List, Optional
from pydantic import BaseModel, Field


class ModuleDoc(BaseModel):
    module_path: str
    docstring: Optional[str] = None
    classes: List[str] = Field(default_factory=list)
    functions: List[str] = Field(default_factory=list)


class WikiManager:
    """Compiles living technical documentation directly from repository source code."""

    def __init__(self, root_dir: Optional[Path] = None, output_dir: Optional[Path] = None):
        self.root_dir = root_dir or Path("./antimatter").resolve()
        self.output_dir = output_dir or Path("./docs/wiki").resolve()

    def scan_module(self, file_path: Path) -> ModuleDoc:
        """Parses a single Python file into a structured ModuleDoc."""
        rel_path = file_path.as_posix()
        try:
            content = file_path.read_text(encoding="utf-8")
            tree = ast.parse(content)
        except Exception:
            return ModuleDoc(module_path=rel_path)

        docstring = ast.get_docstring(tree)
        classes = []
        functions = []

        for node in tree.body:
            if isinstance(node, ast.ClassDef):
                classes.append(node.name)
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                functions.append(node.name)

        return ModuleDoc(
            module_path=rel_path,
            docstring=docstring,
            classes=classes,
            functions=functions,
        )

    def scan_repository(self) -> List[ModuleDoc]:
        """Scans all Python files under root_dir."""
        modules = []
        if not self.root_dir.exists():
            return modules

        for py_file in sorted(self.root_dir.rglob("*.py")):
            if "__pycache__" in py_file.parts:
                continue
            modules.append(self.scan_module(py_file))
        return modules

    def generate_index_markdown(self, modules: List[ModuleDoc]) -> str:
        """Generates a comprehensive wiki index with a Mermaid system diagram."""
        lines = [
            "# Project Antimatter — Living Technical Wiki",
            "",
            "> ⚡ Autogenerated from live codebase AST analysis.",
            "",
            "## Architecture Overview",
            "",
            "```mermaid",
            "graph TD",
            "    Core[antimatter.core] --> Brain[antimatter.brain]",
            "    Brain --> Swarm[antimatter.agent.swarm]",
            "    Swarm --> Tools[antimatter.tools]",
            "    Tools --> API[antimatter.api]",
            "    API --> Client[client.tauri]",
            "```",
            "",
            "## Module Index",
            "",
            "| Module Path | Primary Classes | Primary Functions | Description |",
            "|---|---|---|---|",
        ]

        for m in modules:
            cls_str = ", ".join(f"`{c}`" for c in m.classes[:3]) or "—"
            fn_str = ", ".join(f"`{f}`" for f in m.functions[:3]) or "—"
            doc_snippet = (m.docstring or "No module docstring.").split("\n")[0][:80].replace("|", "\\|")
            lines.append(f"| `{m.module_path}` | {cls_str} | {fn_str} | {doc_snippet} |")

        lines.append("")
        return "\n".join(lines)

    def build_wiki(self) -> Path:
        """Builds and writes the wiki index to disk."""
        self.output_dir.mkdir(parents=True, exist_ok=True)
        modules = self.scan_repository()
        content = self.generate_index_markdown(modules)
        index_file = self.output_dir / "README.md"
        index_file.write_text(content, encoding="utf-8")
        return index_file
