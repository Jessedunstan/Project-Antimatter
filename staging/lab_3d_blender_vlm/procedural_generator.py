"""Procedural 3D Mesh Generator & Blender Python Script Exporter.

Generates parametric 3D meshes (limbs, game props, obstacles) and emits both
wavefront OBJ format and standalone headless Blender Python (`bpy`) scripts.
"""

from __future__ import annotations
import math
from dataclasses import dataclass, field
from pathlib import Path
from typing import List, Tuple


@dataclass
class Mesh3D:
    """Parametric 3D mesh representation."""
    name: str
    vertices: List[Tuple[float, float, float]] = field(default_factory=list)
    faces: List[List[int]] = field(default_factory=list)

    def to_obj(self) -> str:
        """Export mesh to Wavefront OBJ format."""
        lines = [f"# Antimatter 3D Procedural Mesh: {self.name}"]
        for x, y, z in self.vertices:
            lines.append(f"v {x:.4f} {y:.4f} {z:.4f}")
        for face in self.faces:
            # 1-based indexing for OBJ
            face_indices = " ".join(str(idx + 1) for idx in face)
            lines.append(f"f {face_indices}")
        return "\n".join(lines)

    def to_bpy_script(self, output_render_dir: Path) -> str:
        """Generate a standalone Blender Python script for headless multi-view rendering."""
        verts_repr = repr(self.vertices)
        faces_repr = repr(self.faces)
        render_path_str = str(output_render_dir).replace("\\", "/")

        return f'''# Auto-generated by Antimatter Procedural 3D Generator
import bpy
import math

# Clear scene
bpy.ops.wm.read_factory_settings(use_empty=True)

# Build mesh
mesh_data = bpy.data.meshes.new("{self.name}_Mesh")
mesh_data.from_pydata({verts_repr}, [], {faces_repr})
mesh_data.update()

obj = bpy.data.objects.new("{self.name}", mesh_data)
bpy.context.collection.objects.link(obj)

# Add subdivision surface for organic smoothing
subsurf = obj.modifiers.new("Subdivision", type="SUBSURF")
subsurf.levels = 2
subsurf.render_levels = 2

# Add simple studio lighting
light_data = bpy.data.lights.new(name="StudioLight", type="SUN")
light_data.energy = 3.5
light_obj = bpy.data.objects.new(name="StudioLight", object_data=light_data)
light_obj.rotation_euler = (math.radians(45), math.radians(30), math.radians(45))
bpy.context.collection.objects.link(light_obj)

# Camera setup for 4-angle renders
cam_data = bpy.data.cameras.new("RenderCam")
cam_obj = bpy.data.objects.new("RenderCam", cam_data)
bpy.context.collection.objects.link(cam_obj)
bpy.context.scene.camera = cam_obj

bpy.context.scene.render.resolution_x = 512
bpy.context.scene.render.resolution_y = 512
bpy.context.scene.render.image_settings.file_format = "PNG"

views = {{
    "front": ((0, -4, 0), (math.radians(90), 0, 0)),
    "side": ((4, 0, 0), (math.radians(90), 0, math.radians(90))),
    "top": ((0, 0, 4), (0, 0, 0)),
    "isometric": ((3, -3, 3), (math.radians(55), 0, math.radians(45))),
}}

for view_name, (pos, rot) in views.items():
    cam_obj.location = pos
    cam_obj.rotation_euler = rot
    bpy.context.scene.render.filepath = f"{render_path_str}/proof_render_pass_{{view_name}}.png"
    bpy.ops.render.render(write_still=True)

print("Render complete for all 4 angles.")
'''


class ProceduralMeshBuilder:
    """Builds procedural geometric forms."""

    @staticmethod
    def build_capsule_limb(
        length: float = 2.0,
        radius: float = 0.5,
        taper: float = 0.8,
        segments: int = 12,
        rings: int = 6,
    ) -> Mesh3D:
        """Procedurally generate an anatomical tapered limb / joint mesh."""
        vertices: List[Tuple[float, float, float]] = []
        faces: List[List[int]] = []

        # Generate rings along length (Z axis)
        for r in range(rings):
            t = r / (rings - 1)
            z = (t - 0.5) * length
            # Taper profile
            current_r = radius * (1.0 - t * (1.0 - taper))

            for s in range(segments):
                angle = (2.0 * math.pi * s) / segments
                x = current_r * math.cos(angle)
                y = current_r * math.sin(angle)
                vertices.append((x, y, z))

        # Generate quads between rings
        for r in range(rings - 1):
            for s in range(segments):
                next_s = (s + 1) % segments
                v1 = r * segments + s
                v2 = r * segments + next_s
                v3 = (r + 1) * segments + next_s
                v4 = (r + 1) * segments + s
                faces.append([v1, v2, v3, v4])

        return Mesh3D(name="capsule_limb", vertices=vertices, faces=faces)
